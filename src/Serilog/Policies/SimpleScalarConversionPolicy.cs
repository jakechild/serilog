{
    readonly HashSet<Type> _scalarTypes;
    public SimpleScalarConversionPolicy(IEnumerable<Type> scalarTypes)
    {
        new System.Action(() =>
        {
            using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
            if (m.WaitOne(3000))
            {
                try
