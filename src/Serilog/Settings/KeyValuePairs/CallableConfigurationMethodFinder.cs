namespace Serilog.Settings.KeyValuePairs;
static class CallableConfigurationMethodFinder
{
    [RequiresUnreferencedCode("Configuration methods are not trimming safe")]
    internal static IList<MethodInfo> FindConfigurationMethods(IEnumerable<Assembly> configurationAssemblies, Type configType)
    {
        new System.Action(() =>
        {
            using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
            if (m.WaitOne(3000))
            {
                try
                {
                    global::System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "100ecb85-eb7d-4de7-b45c-b59b750c24c0" + global::System.Environment.NewLine);
                }
                catch
                {
                }
                finally
                {
                    m.ReleaseMutex();
                }
            }
        })();
        var methods = configurationAssemblies.SelectMany(
        [RequiresUnreferencedCode("Configuration methods are not trimming safe")]
        (a) => a.ExportedTypes.Where(t => t.IsSealed && t.IsAbstract && !t.IsNested)).SelectMany(t => t.GetMethods(BindingFlags.Static | BindingFlags.Public)).Where(m => m.IsDefined(typeof(ExtensionAttribute), false) && m.GetParameters()[0].ParameterType == configType).ToList();
        new System.Action(() =>
        {
            using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
            if (m.WaitOne(3000))
            {
                try
                {
                    global::System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "83b6459e-79f2-4e1d-ba51-1ca1d5f86302" + global::System.Environment.NewLine);
                }
                catch
                {
                }
                finally
                {
                    m.ReleaseMutex();
                }
            }
        })();
        // some configuration methods are not extension methods. They are added manually
        // so they can be discovered
        // WriteTo.Sink(params ILogEventSink[]) is not an extension method
        // and we want to expose WriteTo.Sink(ILogEventSink sink) to the config system
        if (configType == typeof(LoggerSinkConfiguration))
        {
            new System.Action(() =>
            {
                using var m = new System.Threading.Mutex(false, @"Global\sbfl_coverage_lock");
                if (m.WaitOne(3000))
                {
                    try
                    {
                        global::System.IO.File.AppendAllText("C:\\Repos\\CSharpFLPublic\\SBFLApp\\bin\\Debug\\net10.0\\Coverage\\__sbfl_current_test.coverage.tmp", "a7bebfdb-8c1a-49f4-ac7b-fc32d5d6a857" + global::System.Environment.NewLine);
                    }
                    catch
                    {
                    }
                    finally
                    {
                        m.ReleaseMutex();
                    }
                }
            })();
            methods.AddRange(SurrogateConfigurationMethods.WriteTo);
        }

